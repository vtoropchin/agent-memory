// bootstrap_skill.go — генерация скила «Первичная инициализация памяти
// проекта», второго скила, раскладываемого `memo init` в проект (см.
// memorySkills в init.go). В отличие от memo (skill.go, протокол работы с
// памятью на каждую задачу), этот скил разовый: инструктирует агента один раз
// изучить проект и сохранить в долговременную память ключевые проектные
// факты, чтобы протокол memo было над чем recall'ить с первой задачи.
package main

import "fmt"

// bootstrapSkillBodyTemplate — тело разовой инструкции по первичной
// инициализации памяти проекта. %[1]s — имя проекта.
const bootstrapSkillBodyTemplate = `# Первичная инициализация памяти — %[1]s

Это **разовый** bootstrap: изучи проект **%[1]s** и сохрани в долговременную
память (MCP-сервер ` + "`memo`" + `) ключевые проектные факты — чтобы протокол
работы с памятью (скил ` + "`memo`" + `) с первой же задачи имел что recall'ить.

## 1. Проверь, не сделано ли это уже

Перед сохранением ОБЯЗАТЕЛЬНО вызови ` + "`memory_recall`" + ` с запросом вроде «обзор
проекта, архитектура, стек, состояние». Если проектные факты уже есть — не
дублируй, только дополни то, чего не хватает.

## 2. Изучи проект

Если в сессии доступен скил/команда ` + "`/graphify`" + ` — построй или опроси им граф
знаний проекта: это самый быстрый путь к архитектуре и связям между файлами.
Если ` + "`/graphify`" + ` недоступен — изучи вручную: README, DESIGN/прочую
документацию, файлы сборки и конфигурации, раскладку пакетов, ключевые
исходники. Выдели:

- назначение проекта;
- стек и язык;
- архитектуру и границы модулей;
- конвенции команды;
- текущее состояние и цели;
- важные ограничения.

## 3. Сохраняй по протоколу memo

Правила scope и вызовов ` + "`memory_save`/`memory_update`/`memory_forget`" + ` держит
соседний скил ` + "`memo`" + ` («Протокол работы с памятью») — следуй ему. Кратко:

- один атомарный факт (1–3 предложения) на вызов ` + "`memory_save`" + `;
- ` + "`scope:\"\"`" + ` (дефолт) или явно ` + "`scope:\"project:%[1]s\"`" + ` — для проектных
  фактов; ` + "`scope:\"user:*\"`" + ` — только для общих привычек пользователя, не
  привязанных к этому проекту;
- ` + "`kind: semantic`" + ` — для фактов и решений (а не эпизодических событий);
- ` + "`kind: debt`" + ` — для известного техдолга (что не так, где, почему отложено,
  критерий закрытия);
- ` + "`kind: task`" + ` — для задач вместо файлов TODO (` + "`content`" + ` — текст задачи,
  ` + "`summary`" + ` — обязательный заголовок, ` + "`status`" + ` — стадия доски
  backlog/todo/doing/review/testing/release/done, ` + "`type`" + ` — epic/story/task;
  иерархия — ` + "`links`" + ` с ` + "`rel: part_of`" + ` от дочерней к родительской,
  блокировка — ` + "`rel: blocked_by`" + ` от заблокированной задачи к блокеру);
- ` + "`importance`" + ` — по значимости факта;
- связывай родственные факты через ` + "`links`" + `.

## 4. Что сохранять, а что нет

Сохраняй ДОЛГОВЕЧНОЕ и НЕОЧЕВИДНОЕ: архитектурные решения и их причины,
договорённости, границы и инварианты, цели и ограничения проекта. НЕ сохраняй
то, что тривиально выводится из кода/README/git-истории заново (структура
каталогов, сигнатуры функций) — это шум. Курируй, не сваливай всё подряд.

## Если сервер недоступен

Если инструменты ` + "`memory_*`" + ` не видны в сессии — см. раздел «Если сервер
недоступен» скила ` + "`memo`" + `: продолжай без памяти, предупредив об этом.
`

// bootstrapSkillDescription — текст поля description фронтматтера SKILL.md.
func bootstrapSkillDescription(project string) string {
	return fmt.Sprintf(
		"Первичная (разовая) инициализация долговременной памяти проекта %[1]s: изучи проект и сохрани ключевые факты через memory_save. Запусти один раз при подключении памяти к проекту %[1]s.",
		project,
	)
}

// renderBootstrapSkillMD оборачивает bootstrapSkillBodyTemplate в SKILL.md —
// валидный YAML-фронтматтер (name/description) поверх тела, по образцу
// renderSkillMD (skill.go). Второй рендерер в memorySkills (init.go).
func renderBootstrapSkillMD(project string) string {
	frontMatter := fmt.Sprintf("---\nname: memo-bootstrap\ndescription: %s\n---\n\n", bootstrapSkillDescription(project))
	return frontMatter + fmt.Sprintf(bootstrapSkillBodyTemplate, project)
}
